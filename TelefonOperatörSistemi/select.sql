SELECT 
    T.ISIM AS TARIFE_ADI,
    COUNT(DISTINCT A.TC_KIMLIK_NO) AS TOPLAM_AKTIF_ABONE_SAYISI,
    COUNT(DISTINCT CASE WHEN IL.AD = 'Yalova' THEN A.TC_KIMLIK_NO END) AS YALOVA_AKTIF_ABONE_SAYISI,
    COUNT(DISTINCT CASE WHEN DATEDIFF(YEAR, A.DOGUM_TARIHI, GETDATE()) < 30 THEN A.TC_KIMLIK_NO END) AS YAS_ALTI_30_AKTIF_ABONE_SAYISI
FROM 
    TARIFELER T
    JOIN SOZLESME_PAKETI SP ON T.TARIFE = SP.TARIFE_ID
    JOIN ABONELIKSOZLESMESI_SOZLESMEPAKETI ASP ON SP.PAKET_ID = ASP.PAKET_ID
    JOIN ABONELIK_SOZLESMESI ASZ ON ASP.SOZLESME_NUMARASI = ASZ.SOZLESME_NUMARASI
    JOIN ABONE A ON ASZ.TC_KIMLIK_NO = A.TC_KIMLIK_NO
    LEFT JOIN ADRES ADR ON A.TC_KIMLIK_NO = ADR.TC_KIMLIK_NO
    LEFT JOIN IL IL ON ADR.IL_ID = IL.IL_ID
WHERE 
    ASZ.IPTAL_TARIHI IS NULL
GROUP BY 
    T.ISIM
ORDER BY 
    TOPLAM_AKTIF_ABONE_SAYISI DESC, 
    YALOVA_AKTIF_ABONE_SAYISI DESC, 
    YAS_ALTI_30_AKTIF_ABONE_SAYISI DESC;
CREATE TABLE ABONE(
	TC_KIMLIK_NO CHAR(11) PRIMARY KEY CHECK (TC_KIMLIK_NO LIKE '[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]') ,
	AD VARCHAR(57) NOT NULL,
	SOYAD VARCHAR(30) NOT NULL,
	DOGUM_TARIHI DATE NOT NULL,
	YAS AS DATEDIFF(yy,DOGUM_TARIHI,GETDATE()),
	MESLEK_ID INT FOREIGN KEY REFERENCES  MESLEK(MESLEK_ID) 
);


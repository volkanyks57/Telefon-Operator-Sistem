    TELEFON_NO CHAR(11) CONSTRAINT chkTel CHECK (TELEFON_NO LIKE '[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]') PRIMARY KEY, 
    DURUM BIT NOT NULL DEFAULT 0,
	TC_KIMLIK_NO CHAR(11) FOREIGN KEY REFERENCES  ABONE(TC_KIMLIK_NO)
